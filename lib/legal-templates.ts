export function legalTemplateFields(content: string) {
  return [...new Set(Array.from(content.matchAll(/\{\{([^{}]+)\}\}/g), match => match[1]))];
}

export function renderLegalTemplate(content: string, details: LegalDetails) {
  return content.replace(/\{\{([^{}]+)\}\}/g, (marker, key: string) =>
    Object.hasOwn(legalFields, key) && details[key]?.trim() ? details[key] : marker);
}
