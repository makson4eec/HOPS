import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import path from "node:path";
function fixture(mode: string) {
  execFileSync(process.execPath, ["--conditions=react-server", "--import", "tsx", "tests/fixtures/commerce.ts", mode], { env: { ...process.env, HOPS_DATA_DIR: process.env.HOPS_DATA_DIR || path.resolve(".test-data/e2e") }, windowsHide: true });
}
test.beforeAll(() => { if (process.env.HOPS_E2E_LOCAL === "true") { fixture("reset"); fixture("setup"); } });
test.afterAll(() => { if (process.env.HOPS_E2E_LOCAL === "true") fixture("reset"); });
test("JSON catalog, pickup, reviews, admin and private loyalty work together", async ({ page, context, browser }) => {
  test.skip(process.env.HOPS_E2E_LOCAL !== "true", "Requires isolated local server");
  test.setTimeout(60000);
  await context.addInitScript(() => sessionStorage.setItem("hops_age_confirmed", "true"));
  await page.goto("/account");
  await page.locator("#login-email").fill("commerce@example.test");
  await page.locator("#login-password").fill("e2e-shop-passphrase");
  await page.getByRole("button", { name: "Войти", exact: true }).click();
  await expect(page.getByRole("button", { name: "Выйти", exact: true })).toBeVisible();
  await page.goto("/loyalty");
  await expect(page.locator(".balance-card strong")).toHaveText("111 Б");
  await expect(page.locator("main")).toContainText("Только личная операция");
  await expect(page.locator("main")).not.toContainText("999");
  await page.goto("/catalog?q=e2e");
  await expect(page.getByRole("button", { name: "Покупка в магазине" })).toBeDisabled();
  const draftBeer = page.locator(".product-card").filter({ hasText: "e2e-beer" });
  await expect(draftBeer.locator(".price")).toContainText("/ л");
  await draftBeer.getByRole("heading", { name: "e2e-beer" }).getByRole("link").click();
  await expect(page.locator("main")).toContainText("7,5 л");
  await expect(page.locator(".detail-list")).toContainText("Тестовый производитель");
  await expect(page.locator(".detail-list")).toContainText("4,5%");
  await expect(page.getByRole("button", { name: "Добавить в корзину" })).toHaveCount(0);
  await page.goto("/catalog?q=e2e");
  await page.locator(".product-card").filter({ hasText: "e2e-snacks" }).getByRole("button", { name: "В корзину" }).click();
  await expect(page.getByRole("link", { name: "Корзина, товаров: 1", exact: true })).toBeVisible();
  await page.goto("/cart");
  await expect(page.locator("main")).toContainText("e2e-snacks");
  await page.getByRole("link", { name: "Оформить самовывоз" }).click();
  await page.locator("#checkout-phone").fill("+79991234567");
  const wall = new Date(Date.now() + 5 * 3600000 + 3600000);
  if (wall.getUTCHours() < 11) wall.setUTCHours(11, 0, 0, 0);
  if (wall.getUTCHours() >= 23) { wall.setUTCDate(wall.getUTCDate() + 1); wall.setUTCHours(11, 0, 0, 0); }
  wall.setUTCMinutes(Math.ceil(wall.getUTCMinutes() / 15) * 15, 0, 0);
  await page.locator("#checkout-time").fill(wall.toISOString().slice(0, 16));
  await page.locator('main input[name="consent"]').check();
  await page.getByRole("button", { name: "Подтвердить самовывоз" }).click();
  await expect(page).toHaveURL(/\/orders\?order=/);
  await expect(page.locator("main")).toContainText("e2e-snacks");
  await page.goto("/reviews");
  await page.locator("#review-text").fill("Отзыв о проверке локального JSON магазина");
  await page.locator('main input[name="consent"]').check();
  await page.getByRole("button", { name: "Отправить отзыв" }).click();
  await expect(page.locator("main").getByRole("status")).toContainText("отправлен");
  const staff = await browser.newContext({ baseURL: process.env.PLAYWRIGHT_BASE_URL || "http://localhost:3000" });
  try {
    await staff.addInitScript(() => sessionStorage.setItem("hops_age_confirmed", "true"));
    const admin = await staff.newPage(); await admin.goto("/account");
    await admin.locator("#login-email").fill("commerce-admin@example.test");
    await admin.locator("#login-password").fill("e2e-shop-passphrase");
    await admin.getByRole("button", { name: "Войти", exact: true }).click();
    await expect(admin.getByRole("button", { name: "Выйти", exact: true })).toBeVisible();
    await admin.goto("/admin?tab=orders");
    await expect(admin.locator("main")).toContainText("e2e-snacks");
    await admin.goto("/admin?tab=products");
    await admin.getByRole("link", { name: "Редактировать e2e-snacks" }).click();
    await admin.getByLabel("Название").fill("e2e-snacks вручную");
    await admin.getByLabel("Цена, ₽").fill("99,90");
    await admin.getByLabel("Физический остаток до вычета резервов").fill("3");
    await admin.getByRole("button", { name: "Сохранить карточку" }).click();
    await expect(admin.getByRole("status")).toContainText("сохранены");
    await page.goto("/catalog?q=e2e-snacks");
    await expect(page.locator(".product-card")).toContainText("e2e-snacks вручную");
    await expect(page.locator(".product-card .price")).toContainText("99,90");
    await page.goto("/availability");
    await expect(page.getByRole("row").filter({ hasText: "e2e-snacks вручную" })).toContainText("2 шт.");

    await admin.goto("/admin?tab=products&edit=new");
    await admin.getByLabel("Название").fill("e2e-временный товар");
    await admin.getByLabel("Категория", { exact: true }).selectOption("snacks");
    await admin.getByLabel("Цена, ₽").fill("10");
    await admin.getByLabel("Физический остаток до вычета резервов").fill("5");
    await admin.getByRole("button", { name: "Сохранить карточку" }).click();
    await expect(admin).toHaveURL(/edit=[0-9a-f-]{36}$/);
    await page.goto("/catalog?q=e2e-временный");
    await expect(page.getByRole("button", { name: "Покупка в магазине" })).toBeDisabled();

    fixture("balance-only");
    await page.goto("/catalog?q=e2e");
    await expect(page.locator(".product-card").filter({ hasText: "e2e-snacks" })).toContainText("42,50");
    await expect(page.locator("main")).not.toContainText("вручную");
    await expect(page.locator("main")).not.toContainText("e2e-временный товар");
    await page.goto("/availability");
    await expect(page.getByRole("row").filter({ hasText: "e2e-snacks" })).toContainText("9 шт.");
    await expect(page.getByRole("row").filter({ hasText: "e2e-beer" })).toContainText("7,5 л");
    await page.goto("/loyalty");
    await expect(page.locator(".balance-card strong")).toHaveText("111 Б");
    await expect(page.getByRole("heading", { name: "История операций пока недоступна" })).toBeVisible();
    await admin.goto("/admin?tab=reviews");
    await admin.locator('main select[name="status"]').selectOption("APPROVED");
    await admin.getByLabel("В тексте нет персональных данных").check();
    await admin.getByRole("button", { name: "Сохранить решение" }).click();
    await expect(admin.locator("main").getByRole("status")).toContainText("сохранены");
    await page.goto("/reviews");
    await expect(page.locator(".review-card")).toContainText("Отзыв о проверке");
    await expect(page.locator(".review-card")).toContainText("Покупатель HOPS");
    await admin.goto("/admin?tab=sync");
    await expect(admin.locator("main")).toContainText("Локальная синхронизация");
    await admin.goto("/admin?tab=settings");
    await expect(admin.locator('textarea[name="loyaltyRules"]')).toBeVisible();

    await admin.goto("/admin?tab=documents");
    const cookiesDoc = admin.locator("section.panel").filter({ has: admin.getByRole("heading", { name: "Cookie и данные браузера", exact: true }) });
    await cookiesDoc.getByLabel("Опубликовать документ").check();
    await cookiesDoc.getByRole("button", { name: "Сохранить документ" }).click();
    await expect(cookiesDoc.getByRole("alert")).toContainText("Заполните поля перед публикацией");

    const details = admin.locator("section.panel").filter({ has: admin.getByRole("heading", { name: "Данные для документов HOPS", exact: true }) });
    await details.getByText("Реквизиты продавца", { exact: true }).click();
    await details.getByLabel("Полное наименование ООО или ИП и его ФИО").fill("ООО Тестовый магазин");
    await details.getByLabel("Публичный адрес сайта (HTTPS)").fill("https://hops.example.test");
    await details.getByText("Персональные данные", { exact: true }).click();
    await details.getByLabel("Электронная почта для запросов по персональным данным и отзыва согласий").fill("privacy@example.test");
    await details.getByLabel("Привлечённые сервисы", { exact: false }).fill("Внешние сервисы отсутствуют");
    await details.getByRole("button", { name: "Сохранить данные для документов" }).click();
    await expect(details.getByRole("status")).toContainText("сохранены");
    await cookiesDoc.getByLabel("Опубликовать документ").check();
    await cookiesDoc.getByRole("button", { name: "Сохранить документ" }).click();
    await expect(cookiesDoc.getByRole("link", { name: "Открыть опубликованный документ" })).toBeVisible();
    await page.goto("/legal?doc=cookies");
    await expect(page.locator(".legal-text")).toContainText("ООО Тестовый магазин");
    await expect(page.locator(".legal-text")).not.toContainText("{{");
  } finally { await staff.close(); }
});
